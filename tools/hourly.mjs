/* Packs hourly weather into src/data/hourly.js: for each file, every hour of
   the year's direct normal irradiance (W/m2) and dry-bulb temperature (0.1 C),
   as base64 Int16 arrays - small enough to ride inside the single-file build.

   Run:  node tools/hourly.mjs   (reads weather/*.epw)

   An EPW row's hour 1 covers 00:00-01:00 local standard time, so index
   (doy - 1) * 24 + (hour - 1) covers hour h .. h + 1 of that day, in PST.    */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const FILES = { gw10: 'weatherfile-fsstat-typical-year-gw1.0-1108395.epw', gw20: 'weatherfile-fsstat-typical-year-gw2.0-1108395.epw' };
const out = {};
for (const [key, name] of Object.entries(FILES)) {
  const rows = readFileSync('weather/' + name, 'utf8').split(/\r?\n/).slice(8).filter(r => r.trim());
  if (rows.length !== 8760) throw new Error(name + ': ' + rows.length + ' hourly rows, expected 8760');
  const dni = new Int16Array(8760), db = new Int16Array(8760);
  rows.forEach((r, i) => {
    const f = r.split(',');
    const t = +f[6], n = +f[14];
    db[i] = Math.round(t * 10);
    dni[i] = n >= 9999 ? 0 : Math.round(n);
  });
  const b64 = a => Buffer.from(a.buffer).toString('base64');
  out[key] = { file: name, dni: b64(dni), db: b64(db) };
  const sum = dni.reduce((a, b) => a + b, 0) / 1000;
  console.log(key, name, 'DNI', sum.toFixed(0), 'kWh/m2 a year, dry bulb', (Math.min(...db) / 10).toFixed(1), 'to', (Math.max(...db) / 10).toFixed(1), 'C');
}
writeFileSync('src/data/hourly.js', `/* Every hour of the two NRC future-shifted typical years for Vancouver Intl A
 * (station 1108395): direct normal irradiance in W/m2 and dry-bulb temperature
 * in tenths of a degree, as base64 little-endian Int16 arrays of 8760 values,
 * index (doy - 1) * 24 + h covering hour h..h+1 in Pacific Standard Time.
 * Generated by tools/hourly.mjs from weather/*.epw; do not edit by hand. */
export const HOURLY_RAW = ${JSON.stringify(out)};
`);
console.log('wrote src/data/hourly.js');
void readdirSync;
